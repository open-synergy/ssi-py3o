    def test_long_unbroken_run_gets_wrap_points(self):
        """Break a long spaceless run with invisible zero-width spaces.

        Regression guard: a long unbroken token (e.g. pasted text with
        no spaces) has no natural word-wrap point, forcing
        LibreOffice's PDF export into a character-level forced-wrap
        fallback for that one line -- confirmed (against Atril/MATE's
        poppler-based viewer) to make some renderers mis-compute that
        line's height and visually overlap the next line. Inserting a
        zero-width space every 20 characters gives it normal
        word-wrap points instead.

        Pure Python -- trigger P1 (L-01: asserting the return value
        of ``_get_html_text``, not a record side effect).
        """
        result = str(self.engine._get_html_text("<p>%s</p>" % ("a" * 45)))
        self.assertEqual(result, "​".join(["a" * 20, "a" * 20, "a" * 5]))

