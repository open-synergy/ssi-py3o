        self.assertEqual(
            result,
            "</text:span></text:p>"
            '<text:list text:style-name="OdooUL">'
            '<text:list-item><text:p text:style-name="OdooListItem">A</text:p>'
            "</text:list-item>"
            '<text:list-item><text:p text:style-name="OdooListItem">B</text:p>'
            "</text:list-item>"
            "</text:list>"
            "<text:p><text:span>",
        )

